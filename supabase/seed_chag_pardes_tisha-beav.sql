### A diferença entre Yom Kippur e Tisha B'Av

Ambos são jejuns de 25 horas com cinco aflições. Mas:

▸ **Yom Kippur**: jejum de **expiação dos pecados pessoais**. Termina em alegria (perdão obtido). Veste-se **branco** (kittel).

